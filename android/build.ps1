# Builds out\PhoneAsController.apk with the Android SDK tools directly (no Gradle). Run: powershell -ExecutionPolicy Bypass -File build.ps1
$ErrorActionPreference = 'Stop'

# ---- App identity (single source of truth) ----
$Package     = 'com.phoneascontroller.app'
$VersionCode = 1
$VersionName = '1.0'
$MinSdk      = 26
$TargetSdk   = 35

# ---- Paths ----
$Here    = $PSScriptRoot
$Build   = Join-Path $Here 'build'
$Out     = Join-Path $Here 'out'
$Apk     = Join-Path $Out 'PhoneAsController.apk'
# Signing material lives OUTSIDE the repo: <repo>\..\android-signing  (d:\PhoneController\android-signing)
$SignDir = if ($env:PAC_SIGNING_DIR) { $env:PAC_SIGNING_DIR } else { Join-Path (Split-Path (Split-Path $Here -Parent) -Parent) 'android-signing' }
$Keystore = Join-Path $SignDir 'phoneascontroller.jks'
$PassFile = Join-Path $SignDir 'password.txt'
$Alias    = 'phoneascontroller'

$Sdk = if ($env:ANDROID_HOME) { $env:ANDROID_HOME } elseif ($env:ANDROID_SDK_ROOT) { $env:ANDROID_SDK_ROOT } else { Join-Path $env:LOCALAPPDATA 'Android\Sdk' }
$BuildTools = Join-Path $Sdk 'build-tools\35.0.0'
if (-not (Test-Path $BuildTools)) { $BuildTools = (Get-ChildItem (Join-Path $Sdk 'build-tools') | Sort-Object Name | Select-Object -Last 1).FullName }
$AndroidJar = Join-Path $Sdk "platforms\android-$TargetSdk\android.jar"
if (-not (Test-Path $AndroidJar)) { throw "Missing $AndroidJar" }

$Aapt2     = Join-Path $BuildTools 'aapt2.exe'
$Aapt      = Join-Path $BuildTools 'aapt.exe'
$D8        = Join-Path $BuildTools 'd8.bat'
$Zipalign  = Join-Path $BuildTools 'zipalign.exe'
$Apksigner = Join-Path $BuildTools 'apksigner.bat'
function JdkTool($name) {
    if ($env:JAVA_HOME -and (Test-Path (Join-Path $env:JAVA_HOME "bin\$name.exe"))) { return Join-Path $env:JAVA_HOME "bin\$name.exe" }
    return (Get-Command $name).Source
}
$Javac   = JdkTool 'javac'
$Keytool = JdkTool 'keytool'

function Run($exe) {
    & $exe @args
    if ($LASTEXITCODE -ne 0) { throw "$([IO.Path]::GetFileName($exe)) failed (exit $LASTEXITCODE)" }
}

# ---- Signing key: create once, then always reuse (updates MUST be signed with the same key) ----
if (-not (Test-Path $Keystore)) {
    Write-Host "Creating release keystore at $Keystore"
    New-Item -ItemType Directory -Force $SignDir | Out-Null
    $chars = [char[]]'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
    $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
    $bytes = New-Object byte[] 32; $rng.GetBytes($bytes)
    $pw = -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
    [IO.File]::WriteAllText($PassFile, $pw)   # no BOM, no newline
    Run $Keytool -genkeypair -keystore $Keystore -storetype PKCS12 -alias $Alias -keyalg RSA -keysize 2048 -validity 10000 `
        -storepass $pw -keypass $pw -dname 'CN=PhoneAsController, O=PhoneAsController'
}
if (-not (Test-Path $PassFile)) { throw "Keystore exists but $PassFile is missing" }

# ---- Clean ----
if (Test-Path $Build) { Remove-Item -Recurse -Force $Build }
New-Item -ItemType Directory -Force $Build, $Out, "$Build\gen", "$Build\classes", "$Build\dex" | Out-Null

# ---- Resources ----
Write-Host '[1/6] aapt2 compile + link'
Run $Aapt2 compile --dir (Join-Path $Here 'res') -o "$Build\res.zip"
Run $Aapt2 link -I $AndroidJar --manifest (Join-Path $Here 'AndroidManifest.xml') `
    --min-sdk-version $MinSdk --target-sdk-version $TargetSdk --version-code $VersionCode --version-name $VersionName `
    -o "$Build\unsigned.apk" "$Build\res.zip"

# ---- Java ----
Write-Host '[2/6] javac'
$buildInfo = "// Generated by build.ps1.`npackage $Package;`n`nfinal class BuildInfo {`n    static final String VERSION_NAME = `"$VersionName`";`n    static final int VERSION_CODE = $VersionCode;`n}`n"
[IO.File]::WriteAllText("$Build\gen\BuildInfo.java", $buildInfo)
$sources = @(Get-ChildItem -Recurse (Join-Path $Here 'src') -Filter *.java | ForEach-Object FullName) + "$Build\gen\BuildInfo.java"
# Java 8 language level compiled purely against android.jar (+ lambda stubs; no JDK classes leak in); d8 desugars lambdas.
Run $Javac -source 8 -target 8 -bootclasspath "$AndroidJar;$(Join-Path $BuildTools 'core-lambda-stubs.jar')" -encoding UTF-8 '-Xlint:-options' -nowarn -d "$Build\classes" @sources

# ---- Dex ----
Write-Host '[3/6] d8'
$classes = Get-ChildItem -Recurse "$Build\classes" -Filter *.class | ForEach-Object FullName
Run $D8 --release --min-api $MinSdk --lib $AndroidJar --output "$Build\dex" @classes

# ---- Package ----
Write-Host '[4/6] add classes.dex'
Push-Location "$Build\dex"
try { Run $Aapt add "$Build\unsigned.apk" classes.dex | Out-Null } finally { Pop-Location }

Write-Host '[5/6] zipalign'
Run $Zipalign -p -f 4 "$Build\unsigned.apk" "$Build\aligned.apk"

Write-Host '[6/6] apksigner'
Run $Apksigner sign --ks $Keystore --ks-key-alias $Alias --ks-pass "file:$PassFile" --v4-signing-enabled false `
    --out $Apk "$Build\aligned.apk"
Run $Apksigner verify $Apk

$size = [math]::Round((Get-Item $Apk).Length / 1KB, 1)
Write-Host "OK: $Apk ($size KB)"
